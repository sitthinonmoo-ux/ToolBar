let currentLang = localStorage.getItem('toolbar-lang') || 'th';

function setLang(lang) {
  currentLang = lang === 'en' ? 'en' : 'th';
  localStorage.setItem('toolbar-lang', currentLang);
}

function getLang() {
  return currentLang;
}

// Static UI chrome string lookup. `args` are passed through to function-valued entries.
function t(key, ...args) {
  const entry = STRINGS[currentLang][key];
  if (typeof entry === 'function') return entry(...args);
  return entry !== undefined ? entry : key;
}

// Plugin-authored content (name/description/labels) may be a plain string (untranslated,
// used as-is in both languages) or a { th, en } object — this picks the right side.
function L(value) {
  if (value && typeof value === 'object') return value[currentLang] || value.th || value.en || '';
  return value == null ? '' : value;
}
